#!/usr/bin/env python3
"""pin-piper-voices.py - write src/claude_code_tts/piper_pins.py from Hugging Face, checked twice.

Every Piper voice the installer offers is downloaded from one commit of rhasspy/piper-voices and
refused unless its SHA-256 matches the pin. HTTPS alone is not enough: in October 2026 eight
intermediate CA keys at eMudhra were recoverable from their public certificates, and anyone
holding one could have served a different file under a valid certificate. A pinned digest makes
that swap fail.

For each voice in install.AVAILABLE_VOICES this reads the tree listing at the revision. A model
(.onnx) is a Git LFS file, so the listing carries its SHA-256 and that is the pin. A sidecar
(.onnx.json) is a plain Git blob: it is downloaded, its Git blob id is recomputed and must equal
the listing's oid, and only then is its SHA-256 the pin. Run it on purpose, read the diff.

    pin-piper-voices.py [--revision REV] [--out PATH]    default revision: v1.0.0, resolved to its commit
Exit 0 written, 1 on any mismatch or missing file (nothing written).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

REPO = "rhasspy/piper-voices"
API = f"https://huggingface.co/api/models/{REPO}"
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from claude_code_tts.install import AVAILABLE_VOICES  # noqa: E402


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def git_blob_id(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--revision", default="v1.0.0")
    ap.add_argument("--out", type=Path, default=ROOT / "src" / "claude_code_tts" / "piper_pins.py")
    args = ap.parse_args()

    commit = json.loads(fetch(f"{API}/revision/{args.revision}"))["sha"]
    print(f"{args.revision} -> {commit}")
    pins: dict[str, str] = {}
    problems: list[str] = []
    for name, _gender, _quality, _desc, segment in AVAILABLE_VOICES:
        listing = {e["path"]: e for e in json.loads(fetch(f"{API}/tree/{commit}/{segment}"))}
        onnx = listing.get(f"{segment}/{name}.onnx")
        if not onnx or not (onnx.get("lfs") or {}).get("oid"):
            problems.append(f"{name}.onnx: not an LFS file at {commit}")
        else:
            pins[f"{name}.onnx"] = onnx["lfs"]["oid"]
        side = listing.get(f"{segment}/{name}.onnx.json")
        if not side:
            problems.append(f"{name}.onnx.json: missing at {commit}")
            continue
        data = fetch(f"https://huggingface.co/{REPO}/resolve/{commit}/{segment}/{name}.onnx.json")
        if git_blob_id(data) != side["oid"]:
            problems.append(f"{name}.onnx.json: downloaded bytes do not match the listing's blob id")
            continue
        pins[f"{name}.onnx.json"] = hashlib.sha256(data).hexdigest()
        print(f"  {name}: ok")

    if problems:
        for p in problems:
            print(f"FAIL {p}", file=sys.stderr)
        print(f"{len(problems)} problem(s); {args.out} not written", file=sys.stderr)
        return 1

    lines = [
        '"""SHA-256 of every Piper voice file the installer downloads, at one commit of piper-voices.',
        "",
        "Generated by scripts/pin-piper-voices.py; regenerate on purpose and read the diff. A download",
        "whose digest differs is deleted and refused (install.download_file), and `claude-tts verify`",
        "re-hashes installed voices against this table.",
        '"""',
        "",
        f'PIPER_REVISION = "{commit}"  # {args.revision}',
        f'PIPER_BASE = f"https://huggingface.co/{REPO}/resolve/{{PIPER_REVISION}}"',
        "",
        "PIPER_SHA256: dict[str, str] = {",
        *(f'    "{k}": "{v}",' for k, v in sorted(pins.items())),
        "}",
        "",
    ]
    args.out.write_text("\n".join(lines))
    print(f"wrote {len(pins)} pins to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
